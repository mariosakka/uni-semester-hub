#!/usr/bin/env node
// Writes docs/STRINGS.md: every UI string key with its default text. Run after editing src/strings.js.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const c = { console };
vm.runInNewContext(readFileSync(new URL('../src/strings.js', import.meta.url), 'utf8'), c);
const cell = s => '`' + String(s).replace(/\|/g, '\|').replace(/`/g, "'") + '`';
let out = `# UI strings

Generated by \`node scripts/gen-strings-doc.mjs\` from \`src/strings.js\`. Do not edit by hand.

Override any key in a data set with \`meta.strings\` (plain text, \`{name}\` placeholders stay), and set \`meta.locale\` for weekday/month names:

\`\`\`js
meta: { locale: "ro-RO", strings: { "schedule.backToCurrent": "Înapoi la săptămâna curentă" } }
\`\`\`
`;
let group = '';
for (const [k, v] of Object.entries(c.HUB_STRINGS)) {
  const g = k.split('.')[0];
  if (g !== group) { group = g; out += `\n## ${g}\n\n| Key | Default |\n|---|---|\n`; }
  out += `| \`${k}\` | ${cell(v)} |\n`;
}
writeFileSync(new URL('../docs/STRINGS.md', import.meta.url), out);
console.log(`docs/STRINGS.md: ${Object.keys(c.HUB_STRINGS).length} keys`);
